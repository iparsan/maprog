// Claves públicas de Supabase: local.properties, variables de entorno (GitHub Actions) o supabase.properties
val localProps = Properties().apply {
    listOf("local.properties", "supabase.properties").forEach { name ->
        val f = rootProject.file(name)
        if (f.exists()) f.inputStream().use { load(it) }
    }
}
fun cfg(key: String): String = System.getenv(key) ?: localProps.getProperty(key) ?: ""

